def receiving_endpoints(hab):
    """Return the witnesses and mailboxes authorized by this identifier."""
    if isinstance(hab, GroupHab) or not hab.accepted:
        return set()
    endpoints = set(hab.kever.wits)
    endpoints.update(eid for (_, _, eid), end in hab.db.ends.getTopItemIter(
        keys=(hab.pre, kering.Roles.mailbox)) if end.allowed)
    return endpoints


class MailboxDirector(doing.DoDoer):
    """
    Coordinates the management, routing, and processing of mailboxes and related systems.

    The `MailboxDirector` class integrates various components to handle incoming
    messages, manage subscriptions, and coordinate with verifiers and exchangers. It implements
    a directed workflow for processing messages, handling replies, and managing escrows. Its
    design supports extensive configuration, making it adaptable to different mailbox-related
    use cases.

    Attributes:
        hby: Hierarchical key store manager for managing key-related operations.
        exchanger: Instance for facilitating and managing exchanges between participants.
        rep: Manages replies, including state or record tracking.
        topics: List of topic identifiers for subscriptions or notifications.
        pollers: One poller per local identifier and receiving endpoint.
        cues: Queue or deck for processing cues generated during message handling.
        ims: Default parser buffer. Mailbox frames are passed to the parser separately.
        messages: Queue of (message, commit) pairs from mailbox pollers. commit
            advances the poller's stored topic position once the raw frame is retained.
        rgy: Native registry manager owned by the vault.
        rtr: Router responsible for message routing to appropriate handlers or verifiers.
        rvy: Verifies routes for received messages and processes message verifications.
        kvy: Used for key events and registering reply routes.
        parser: Parses incoming data streams and delegates processing to relevant components.
    """

    def __init__(self, hby, topics, rgy, kvy, exc, db, ims=None,
                 rep=None, cues=None, rvy=None, **kwa):
        """
        Initializes the MailboxDirector class, which is responsible for managing mailboxes,
        routing messages, handling replies, and processing incoming data streams. It ensures
        coordination between different components like verifiers, exchangers, routers, and
        processors.

        Parameters:
            hby: Object responsible for managing the local hierarchical key store.
            topics: Topic identifiers for subscription or notification handling.
            ims: Optional default parser buffer. Mailbox frames use separate buffers.
            kvy: Required key event verifier with a Kramer for pending key evidence.
            exc: Required exchanger for message verification and pending exchanges.
            rep: Optional object for managing reply records or states.
            cues: Optional queue or deck for processing cues generated by the component.
            rvy: Optional router/verifier object for managing received routes.
            rgy: Native registry manager owned by the vault.
            **kwa: Additional keyword arguments passed to the parent class initializer.
        """
        self.hby = hby
        self.db = db
        self.rgy = rgy
        self.exchanger = exc
        self.rep = rep
        self.topics = topics
        self.pollers = list()
        self.cues = cues if cues is not None else decking.Deck()

        self.ims = ims if ims is not None else bytearray()
        self.messages = decking.Deck()

        doers = []
        doers.extend([doing.doify(self.pollDo),
                      doing.doify(self.msgDo),
                      doing.doify(self.escrowDo)])

        self.rtr = routing.Router()
        self.rvy = rvy

        self.kvy = kvy
        self.kvy.registerReplyRoutes(self.rtr)

        self.parser = parsing.Parser(ims=self.ims,
                                     framed=True,
                                     kvy=self.kvy,
                                     exc=self.exchanger,
                                     rvy=self.rvy,
                                     version=kering.Vrsn_2_0)

        super(MailboxDirector, self).__init__(doers=doers, **kwa)

    @property
    def mailboxes(self):
        return oset([(poller.hab.name, poller.hab.pre, poller.mailbox) for poller in self.pollers])

    def wind(self, tymth):
        """
        Bind this director and its child doers to the scheduler clock.

        Args:
            tymth: Callable that returns the scheduler time in seconds.
        """
        super(MailboxDirector, self).wind(tymth)

    def pollDo(self, tymth=None, tock=0.0, **kwa):
        """ Queue complete messages from remote mailbox pollers
         
        Parameters:
            tymth: injected function wrapper closure returned by .tymen() of
                Tymist instance. Calling tymth() returns the associated Tymist .tyme.
            tock (float): injected initial tock value in seconds
            **kwa: additional keyword arguments
         
         """
        # enter context
        self.wind(tymth)
        self.tock = tock
        _ = (yield self.tock)

        while True:
            wanted = {(hab.pre, eid): hab for hab in self.hby.habs.values()
                      for eid in receiving_endpoints(hab)}
            for poller in list(self.pollers):
                if (poller.pre, poller.mailbox) not in wanted:
                    self.remove_poller(poller.hab, poller.mailbox)
            for (pre, eid), hab in wanted.items():
                self.add_poller(hab, eid)
            for item in self.processPollIter():
                self.messages.append(item)
                _ = (yield self.tock)
            _ = (yield 1.0)

    def add_pollers(self, hab):
        """
        Poll every witness and authorized mailbox of an accepted single identifier.

        Group identifiers are not listened for yet.

        Parameters:
            hab: The habitat whose messages are polled.
        """
        for eid in receiving_endpoints(hab):
            self.add_poller(hab, eid)

    def add_poller(self, hab, mailbox):
        """
        Start polling mailbox for hab unless a poller for that pair already runs.

        Parameters:
            hab: The habitat whose messages are polled.
            mailbox: The witness or mailbox prefix to poll.
        """
        if any(poller.pre == hab.pre and poller.mailbox == mailbox for poller in self.pollers):
            return

        poller = Poller(hab=hab, topics=self.topics, mailbox=mailbox)
        self.pollers.append(poller)
        self.extend([poller])

    def processPollIter(self):
        """
        Drain the messages queued by each mailbox poller.

        Yields:
            tuple: (message, commit) where commit records the message's topic
                position after the raw frame is retained.

        """
        mail = []
        for poller in self.pollers:  # get responses from all behaviors
            while poller.msgs:
                msg, topic, idx = poller.msgs.popleft()
                mail.append((msg, functools.partial(poller.commit, topic, idx)))

        while mail:  # iteratively process each response in responses
            msg = mail.pop(0)
            yield msg

    def msgDo(self, tymth=None, tock=0.0, **kwa):
        """
        Parse queued mailbox messages.

        Select the attachment version for each frame before validation.

        Scheduler:
            Wrap this generator with doing.doify to schedule it as a doer.
            Yield the delay before the next scheduler step.

        Parameters:
            tymth is injected function wrapper closure returned by .tymen() of
                Tymist instance. Calling tymth() returns the associated Tymist .tyme.
            tock is injected initial tock value

        Usage:
            Add doing.doify(self.msgDo) to the doers list.
        """
        self.wind(tymth)
        self.tock = tock
        _ = (yield self.tock)

        while True:
            while self.messages:
                msg, commit = self.messages.popleft()
                # Arrival order keeps a sender's KEL ahead of the messages it signs.
                key = (f'{time.time_ns():020d}', Diger(ser=bytes(msg)).qb64)
                self.db.inbox.put(key, MailboxFrame(Texter(raw=bytes(msg)).qb64))
                if commit is not None:
                    commit()
                yield self.tock
            for keys, frame in list(self.db.inbox.getTopItemIter()):
                msg = bytearray(Texter(qb64=frame.raw).raw)
                version = kering.Vrsn_2_0
                try:
                    v1_body = (kering.sniff(msg) == kering.Colds.msg
                               and kering.smell(msg).pvrsn == kering.Vrsn_1_0)
                except kering.KeriError:
                    v1_body = False  # Let the parser discard the malformed frame.
                if v1_body:
                    # V1 bodies do not identify their attachment genus. Extract
                    # the whole frame without validation before choosing V1.
                    try:
                        yield from self.parser.groupParsator(
                            ims=bytearray(msg), framed=True, local=False,
                            version=kering.Vrsn_2_0, processive=False)
                    except Exception:
                        version = kering.Vrsn_1_0
                try:
                    self.parser.parse(ims=msg, version=version, local=False)
                except Exception:
                    logger.exception('Mailbox frame could not be processed')
                # Native processing owns the message once the parser has run.
                self.db.inbox.rem(keys)
                yield self.tock
            yield 1.0

    def escrowDo(self, tymth=None, tock=0.0, **kwa):
        """
        Retry pending key, reply, exchange, and registry evidence.

        Scheduler:
            Wrap this generator with doing.doify to schedule it as a doer.
            Yield the delay before the next scheduler step.

        Parameters:
            tymth is injected function wrapper closure returned by .tymen() of
                Tymist instance. Calling tymth() returns the associated Tymist .tyme.
            tock is injected initial tock value

        Usage:
            Add doing.doify(self.escrowDo) to the doers list.
        """
        self.wind(tymth)
        self.tock = tock
        _ = (yield self.tock)

        while True:
            self.kvy.processEscrows()
            if self.rvy:
                self.rvy.processEscrowReply()
            self.exchanger.processEscrow()
            self.rgy.processEscrows()
            self.kvy.kramer.cues.clear()
            # The vault registry worker consumes proof cues and retries escrow.

            yield

    @property
    def times(self):
        times = dict()
        for poller in self.pollers:  # get responses from all pollers
            times |= poller.times

        return times

    def remove_poller(self, hab, mailbox):
        """
        Remove a Poller instance from the director.

        Finds the poller matching the hab and mailbox, removes it from the pollers list,
        and properly closes it via the DoDoer remove mechanism.

        Parameters:
            hab: The habitat associated with the poller to remove.
            mailbox: The mailbox EID associated with the poller to remove.
        """
        # Find the poller to remove
        poller_to_remove = None
        for poller in self.pollers:
            if poller.hab.pre == hab.pre and poller.mailbox == mailbox:
                poller_to_remove = poller
                break

        if poller_to_remove is not None:
            self.pollers.remove(poller_to_remove)
            self.remove([poller_to_remove])  # This closes the poller via DoDoer.remove()
            logger.info(f"Removed poller for hab={hab.pre}, mailbox={mailbox}")
        else:
            logger.warning(f"No poller found for hab={hab.pre}, mailbox={mailbox}")


class Poller(doing.DoDoer):
    """
    Polls remote SSE endpoint for event that are KERI messages to be processed

    Queued messages are (message, topic, index) tuples. The stored topic position
    advances only through commit, after the director has parsed the message.
    """

    def __init__(self, hab, mailbox, topics, msgs=None, retry=1000, **kwa):
        """
        Initializes an instance of the Poller class.

        Args:
            hab: The habitat instance associated with the poller.
            mailbox: The identifier or locator of the witness to be polled.
            topics: The topics or channels to monitor or poll for events.
            msgs: Optional; a deque or collection of messages to process. Defaults to None.
            retry: Optional; the retry interval in milliseconds. Defaults to 1000.
            **kwa: Additional keyword arguments for customization.
        """
        self.hab = hab
        self.pre = hab.pre
        self.mailbox = mailbox
        self.topics = topics
        self.retry = retry
        self.error = ''
        self.connected = False
        self.msgs = msgs if msgs is not None else decking.Deck()
        self.times = dict()

        doers = [doing.doify(self.eventDo)]

        super(Poller, self).__init__(doers=doers, **kwa)

    def eventDo(self, tymth=None, tock=0.0, **kwa):
        """
        Handles event-driven processing and communication with a witness through HTTP, retrying operations
        based on a given number of attempts and managing message queries and responses.

        Args:
            tymth: A generator function reference for timing control, which facilitates coroutine scheduling or
                task management within the event loop. Defaults to None.
            tock: A float representing the duration of the time slice (in seconds) for processing in the event loop.
                Defaults to 0.0.
            **kwa: Arbitrary keyword arguments that may be provided to the underlying functionality, allowing
                flexibility in extending the method's behavior or integrating with external components.

        Yields:
            float: The duration of sleep intervals or processing delays during various operations, which may vary
                based on the execution context and retry logic.

        """
        self.wind(tymth)
        self.tock = tock
        _ = (yield self.tock)

        witrec = self.hab.db.tops.get((self.pre, self.mailbox))
        if witrec is None:
            witrec = basing.TopicsRecord(topics=dict())

        while self.retry > 0:
            try:
                client, clientDoer = agenting.httpClient(self.hab, self.mailbox)
            except kering.MissingEntryError as e:
                self.error = str(e)
                self.connected = False
                yield max(self.retry / 1000, 5.0)
                continue

            self.extend([clientDoer])
            self.error = ''

            topics = dict()
            q = dict(pre=self.pre, topics=topics)
            for topic in self.topics:
                if topic in witrec.topics:
                    topics[topic] = witrec.topics[topic] + 1
                else:
                    topics[topic] = 0

            # Create query message
            if isinstance(self.hab, GroupHab):
                msg = self.hab.mhab.query(
                    pre=self.pre,
                    src=self.mailbox,
                    route="mbx",
                    query=q,
                    version=kering.Vrsn_2_0,
                    gvrsn=kering.Vrsn_2_0,
                    kind=kering.Kinds.json,
                )  # type: ignore
            else:
                msg = self.hab.query(
                    pre=self.pre,
                    src=self.mailbox,
                    route="mbx",
                    query=q,
                    version=kering.Vrsn_2_0,
                    gvrsn=kering.Vrsn_2_0,
                    kind=kering.Kinds.json,
                )

            httping.createCESRRequest(msg, client, dest=self.mailbox)

            while client.requests:
                yield self.tock

            created = helping.nowUTC()
            while True:

                now = helping.nowUTC()
                if now - created > datetime.timedelta(seconds=30):
                    self.remove([clientDoer])
                    self.connected = False
                    break

                while client.events:
                    self.connected = True
                    evt = client.events.popleft()
                    if "retry" in evt:
                        self.retry = evt["retry"]
                    if "id" not in evt or "data" not in evt or "name" not in evt:
                        logger.error(f"bad mailbox event: {evt}")
                        continue
                    idx = evt["id"]
                    msg = evt["data"]
                    tpc = evt["name"]

                    if idx is None or not msg or tpc not in self.topics:
                        logger.error(f"bad mailbox event: {evt}")
                        continue
                    try:
                        idx = int(idx)
                        if idx < 0:
                            raise ValueError('Negative mailbox position')
                    except (TypeError, ValueError):
                        self.error = 'The mailbox returned an invalid message position.'
                        continue

                    # Only the next query uses this in-memory position. The
                    # stored one waits for commit.
                    witrec.topics[tpc] = idx
                    self.times[tpc] = helping.nowUTC()
                    self.msgs.append((msg.encode("utf-8"), tpc, idx))
                    yield self.tock

                yield 0.25
            yield self.retry / 1000

    def commit(self, topic, idx):
        """
        Store idx as the last processed index for topic, if it is newer.

        Parameters:
            topic (str): mailbox topic of the processed message.
            idx (int): mailbox index of the processed message.
        """
        keys = (self.pre, self.mailbox)
        record = self.hab.db.tops.get(keys)
        if record is None:
            record = basing.TopicsRecord(topics=dict())
        if record.topics.get(topic, -1) < idx:
            record.topics[topic] = idx
            self.hab.db.tops.pin(keys, record)
